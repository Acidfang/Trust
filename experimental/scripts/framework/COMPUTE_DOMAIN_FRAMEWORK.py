@dataclass
class OrientationVector:
    anchor_type: str
    anchor_vector: Tuple[float, float, float]
    magnitude: float
    secondary_moment: Optional[Tuple[float, float, float]] = None
    secondary_magnitude: Optional[float] = None
    properties: Dict[str, Any] = field(default_factory=dict)
    confidence: float = 1.0
    
    def get_orientation_matrix(self) -> List[List[float]]:
        mag = math.sqrt(sum(v**2 for v in self.anchor_vector))
        if mag < 1e-6:
            return [[1, 0, 0], [0, 1, 0], [0, 0, 1]]
        
        Z = tuple(v / mag for v in self.anchor_vector)
        X_temp = (1, 0, 0) if abs(Z[0]) < 0.9 else (0, 1, 0)
        Y = (X_temp[1]*Z[2] - X_temp[2]*Z[1], X_temp[2]*Z[0] - X_temp[0]*Z[2], X_temp[0]*Z[1] - X_temp[1]*Z[0])
        Y_mag = math.sqrt(sum(v**2 for v in Y))
        Y = tuple(v / Y_mag for v in Y)
        X = (Y[1]*Z[2] - Y[2]*Z[1], Y[2]*Z[0] - Y[0]*Z[2], Y[0]*Z[1] - Y[1]*Z[0])
        
        return [list(X), list(Y), list(Z)]


