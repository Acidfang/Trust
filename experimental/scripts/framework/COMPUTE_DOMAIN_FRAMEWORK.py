@dataclass
class ComputeCluster:
    name: str
    nodes: List[ComputeNode] = field(default_factory=list)
    links: List[DataLink] = field(default_factory=list)
    metadata: Dict[str, Any] = field(default_factory=dict)
    
    _node_ids: Set[str] = field(default_factory=set)
    _require_valid_links: bool = True
    
    spatial_grid: Optional[Dict[Tuple[int, int, int], List[str]]] = None
    grid_cell_size: float = 10.0
    
    state_versions: List[Dict] = field(default_factory=list)
    current_version: int = 0
    locked: bool = False
    locked_until: float = 0.0
    
    def add_node(self, node: ComputeNode) -> Tuple[bool, Optional[str]]:
        if self.locked:
            return False, "locked"
        if node.id in self._node_ids:
            return False, f"dup:{node.id}"
        
        self.nodes.append(node)
        self._node_ids.add(node.id)
        
        if self.spatial_grid is not None:
            self._add_to_grid(node)
        
        return True, None
    
    def add_link(self, link: DataLink) -> Tuple[bool, Optional[str]]:
        if self.locked:
            return False, "locked"
        
        if self._require_valid_links:
            src_exists = any(n.id == link.src_id for n in self.nodes)
            dst_exists = any(n.id == link.dst_id for n in self.nodes)
            
            if not src_exists:
                return False, f"src_missing:{link.src_id}"
            if not dst_exists:
                return False, f"dst_missing:{link.dst_id}"
        
        link.exists = True
        link.validated = True
        self.links.append(link)
        return True, None
    
    def _add_to_grid(self, node: ComputeNode) -> None:
        if self.spatial_grid is None:
            self.spatial_grid = {}
        
        cx, cy, cz = node.position
        cell_x, cell_y, cell_z = int(cx/self.grid_cell_size), int(cy/self.grid_cell_size), int(cz/self.grid_cell_size)
        cell_key = (cell_x, cell_y, cell_z)
        
        if cell_key not in self.spatial_grid:
            self.spatial_grid[cell_key] = []
        self.spatial_grid[cell_key].append(node.id)
    
    def nearby_nodes(self, position: Tuple[float, float, float], radius: float) -> List[ComputeNode]:
        if self.spatial_grid is None:
            return []
        
        cx, cy, cz = position
        cell_x, cell_y, cell_z = int(cx/self.grid_cell_size), int(cy/self.grid_cell_size), int(cz/self.grid_cell_size)
        
        nearby_ids = set()
        search_r = int(radius/self.grid_cell_size) + 1
        
        for dx in range(-search_r, search_r + 1):
            for dy in range(-search_r, search_r + 1):
                for dz in range(-search_r, search_r + 1):
                    key = (cell_x + dx, cell_y + dy, cell_z + dz)
                    if key in self.spatial_grid:
                        nearby_ids.update(self.spatial_grid[key])
        
        result = []
        for node in self.nodes:
            if node.id in nearby_ids:
                dx = node.position[0] - cx
                dy = node.position[1] - cy
                dz = node.position[2] - cz
                dist = math.sqrt(dx*dx + dy*dy + dz*dz)
                if dist <= radius:
                    result.append(node)
        
        return result
    
    def detect_cycles(self) -> List[List[str]]:
        cycles = []
        visited = set()
        rec_stack = set()
        
        def dfs(node_id: str, path: List[str]) -> None:
            visited.add(node_id)
            rec_stack.add(node_id)
            path.append(node_id)
            
            for link in self.links:
                if link.src_id == node_id:
                    next_id = link.dst_id
                    if next_id not in visited:
                        dfs(next_id, path[:])
                    elif next_id in rec_stack:
                        cycle_start = path.index(next_id)
                        cycle = path[cycle_start:] + [next_id]
                        cycles.append(cycle)
            
            rec_stack.remove(node_id)
        
        for node in self.nodes:
            if node.id not in visited:
                dfs(node.id, [])
        
        return cycles
    
    def lock(self, duration: float = 60.0) -> None:
        self.locked = True
        self.locked_until = time.time() + duration
    
    def unlock(self) -> None:
        self.locked = False
    
    def snapshot(self) -> None:
        snap = {
            "v": self.current_version,
            "t": time.time(),
            "n": len(self.nodes),
            "l": len(self.links),
            "ids": list(self._node_ids)
        }
        self.state_versions.append(snap)
        self.current_version += 1


def calc_load_centroid(loads: Dict[str, float]) -> OrientationVector:
    if not loads:
        return OrientationVector("load_centroid", (0.5, 0.5, 0.5), 0.0, properties={"d": "compute"})
    
    nc = len(loads)
    gs = int(math.ceil(nc ** (1/3)))
    
    ls = list(loads.values())
    wx = wy = wz = 0.0
    tl = sum(ls)
    
    for i, l in enumerate(ls):
        x = (i % gs) / max(1, gs - 1) if gs > 1 else 0.5
        y = ((i // gs) % gs) / max(1, gs - 1) if gs > 1 else 0.5
        z = (i // (gs * gs)) / max(1, gs - 1) if gs > 1 else 0.5
        
        wx += x * l
        wy += y * l
        wz += z * l
    
    c = (wx / max(0.01, tl), wy / max(0.01, tl), wz / max(0.01, tl))
    
    return OrientationVector(
        "load_centroid",
        c,
        tl / nc if nc > 0 else 0.0,
        properties={"d": "compute", "l": loads, "nc": nc, "tl": tl}
    )


def calc_memory_heat(memory_usage: Dict[str, float]) -> OrientationVector:
    if not memory_usage:
        return OrientationVector("memory_heat", (0.5, 0.5, 0.5), 0.0, properties={"d": "compute"})
    
    mu = list(memory_usage.values())
    avg_m = sum(mu) / len(mu)
    peak_idx = mu.index(max(mu))
    
    peak_pos = (peak_idx * 0.5, 0.5, 1.0)
    
    return OrientationVector(
        "memory_heat",
        peak_pos,
        max(mu),
        properties={"d": "compute", "m": memory_usage, "peak": peak_idx, "avg": avg_m}
    )


def calc_dataflow(nodes: List[ComputeNode], links: List[DataLink]) -> OrientationVector:
    if not links:
        return OrientationVector("dataflow", (1.0, 0.0, 0.0), 0.0, properties={"d": "compute"})
    
    fw = [0.0, 0.0, 0.0]
    total_bw = 0.0
    
    node_map = {n.id: n for n in nodes}
    
    for link in links:
        src = node_map.get(link.src_id)
        dst = node_map.get(link.dst_id)
        
        if src and dst:
            dx = dst.position[0] - src.position[0]
            dy = dst.position[1] - src.position[1]
            dz = dst.position[2] - src.position[2]
            
            mag = math.sqrt(dx*dx + dy*dy + dz*dz)
            if mag > 1e-6:
                dx, dy, dz = dx/mag, dy/mag, dz/mag
            
            fw[0] += dx * link.bandwidth
            fw[1] += dy * link.bandwidth
            fw[2] += dz * link.bandwidth
            total_bw += link.bandwidth
    
    if total_bw > 0:
        fw = tuple(v / total_bw for v in fw)
    else:
        fw = (1.0, 0.0, 0.0)
    
    return OrientationVector(
        "dataflow",
        fw,
        total_bw,
        properties={"d": "compute", "bw": total_bw, "nl": len(links)}
    )


